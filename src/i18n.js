function supportedLanguage(language) {
  return LANGUAGES.some((item) => item.value === language) ? language : "en";
}

export function loadLanguage() {
  const stored = globalThis.localStorage?.getItem("agrisense-language");
  return LANGUAGES.some((item) => item.value === stored) ? stored : "bn";
}

export function persistLanguage(language) {
  const supported = supportedLanguage(language);
  globalThis.localStorage?.setItem("agrisense-language", supported);
  globalThis.document?.documentElement.setAttribute("lang", supported);
  globalThis.document?.documentElement.setAttribute("data-language", supported);
}

export function t(language, key) {
  return COPY[supportedLanguage(language)]?.[key] ?? COPY.en[key] ?? key;
}

export function responseLanguageName(language) {
  if (language === "bn") {
    return "natural, concise Bangla used in Bangladesh, in Bengali script; avoid robotic literal translation";
  }
  return "clear, concise English";
}
